"""Generates the data the web app needs from the processor's own files.

    <rmg_tools>/core/.venv/Scripts/python tools/make_data.py <rmg_tools>/core

Writes:
    dictionary.js          the ArUco codes of the dictionary zones.json names
    layout.js              what stands on the wall: the check-list items and their stickers
    tests/fixtures/*       generated "photos" for the detector tests (drawn by code –
                           never a real photo of the wall)

Run it again whenever zones.json gets a new zone or another dictionary.
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
core = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(core))

from board_worker.zones import KIND_BOARD, KIND_PANEL, load_layout  # noqa: E402
from tests import board_fixtures as fx  # noqa: E402

HEADER = "// Generated by tools/make_data.py – do not edit by hand.\n\n"

# How the wall is shown, left to right (the same order and names as the RMG Tools plugin:
# plugins/bulletin_board/plugin.py – WALL_ROWS, SIDE_WALL, CORK_BOARDS). The last number
# is the line of the phone's wall map (the user's choice): the left row, the right row, then
# the side wall with the two boards (the whole wall in one line would be too small to tap).
GROUPS = [
    ("sor-2", "Bal szekrénysor", 1),
    ("sor-1", "Jobb szekrénysor", 2),
    ("oldalfal", "Oldalfal", 3),
    ("parafa-1", "Nagy parafatábla", 3),
    ("parafa-2", "Kis parafatábla", 3),
]


def rounded(box: dict) -> dict:
    return {key: round(value) for key, value in box.items()}


def write_dictionary(layout) -> None:
    dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, layout.dictionary))
    codes = []
    for marker in range(len(dictionary.bytesList)):
        cells = cv2.aruco.generateImageMarker(dictionary, marker, 6)[1:5, 1:5] > 127
        codes.append(int("".join("1" if bit else "0" for bit in cells.flatten()), 2))
    body = (
        f"// {layout.dictionary}: one number per sticker id – the 4×4 inner cells, row by row,\n"
        "// first cell = highest bit, 1 = white.\n"
        f"export const DICTIONARY = {json.dumps(codes)};\n"
    )
    (ROOT / "dictionary.js").write_text(HEADER + body, encoding="utf-8", newline="\n")


def write_layout(layout) -> None:
    zones = {zone.id: zone for zone in layout.zones}
    groups = []

    def top_down(zone, column):
        # As the stickers really are on the wall (zones.json may record swapped ones).
        return sorted(column, key=lambda marker: zone.markers[marker][1])

    for zone_id, name, line in GROUPS:
        zone = zones[zone_id]
        left = min(door.left_mm for door in zone.doors)
        top = min(door.top_mm for door in zone.doors)
        right = max(door.right_mm for door in zone.doors)
        bottom = max(door.bottom_mm for door in zone.doors)
        items = []
        for door in zone.doors:
            if zone.kind == KIND_BOARD:
                items += board_items(zone, door)
            else:
                items.append({
                    "id": door.id,
                    "label": "oldalfal" if zone.kind == KIND_PANEL else f"{door.number}. ajtó",
                    # A cabinet door can be reported empty with a tap, without a photo.
                    "canBeEmpty": True,
                    "columns": [top_down(zone, column) for column in door.sticker_columns],
                    "box": rounded({
                        "x": door.left_mm - left, "y": door.top_mm - top,
                        "w": door.right_mm - door.left_mm, "h": door.bottom_mm - door.top_mm,
                    }),
                })
        groups.append({
            "id": zone_id, "name": name, "line": line,
            "size": rounded({"w": right - left, "h": bottom - top}),
            "items": items,
        })
    body = (
        "// The check-list. A door (or the side wall) is ticked by a photo that holds at least\n"
        "// 2 stickers of both of its sticker columns (the processor's own rule); the stickers\n"
        "// of a column are listed top to bottom. A piece of a cork board (`stickers`) is the\n"
        "// strip between two neighbouring stickers of its top or bottom edge: a photo that\n"
        "// holds both of them ticks it (the processor needs any 2 stickers of the board).\n"
        "// For the wall map: `size` of a group and `box` of an item in mm (from the group's\n"
        "// top left corner), `line` = the map line. A board's last item (`whole`) is its far\n"
        "// photo: `points` = [id, x_mm, y_mm] of every sticker of the board.\n"
        f"export const MARKER_MM = {layout.marker_mm:g};\n"
        f"export const GROUPS = {json.dumps(groups, ensure_ascii=False, indent=2)};\n"
    )
    (ROOT / "layout.js").write_text(HEADER + body, encoding="utf-8", newline="\n")


def board_items(zone, board) -> list[dict]:
    """A cork board is photographed in half-board pieces (~75 × 55 cm): one item per pair
    of neighbouring stickers of the top edge, then of the bottom edge, left to right."""
    markers = zone.markers
    ys = sorted({y for _, y in markers.values()})
    half = (board.bottom_mm - board.top_mm) / 2
    items = []
    for edge, key, y, box_y in (("felső", "felso", ys[0], 0), ("alsó", "also", ys[-1], half)):
        row = sorted((m for m in board.stickers if markers[m][1] == y),
                     key=lambda m: markers[m][0])
        for index in range(len(row) - 1):
            items.append({
                "id": f"{board.id}-{key}-{index + 1}",
                "label": f"{edge} sor, {index + 1}. rész",
                "stickers": [row[index], row[index + 1]],
                # The strip between the two stickers, its half of the board's height; the
                # first and last strips reach the board's edge.
                "box": rounded({
                    "x": 0 if index == 0 else markers[row[index]][0],
                    "y": box_y,
                    "w": (board.right_mm if index == len(row) - 2 else markers[row[index + 1]][0])
                    - (0 if index == 0 else markers[row[index]][0]),
                    "h": half,
                }),
            })
    # One far photo of the whole board, straight on: the processor lines the close photos up
    # on it (board_worker/doors.py `align`). Every sticker with its place, for the check.
    items.append({
        "id": f"{board.id}-egesz",
        "label": "egész tábla (távoli)",
        "whole": True,
        "points": [[m, round(markers[m][0]), round(markers[m][1])] for m in board.stickers],
    })
    return items


def save_fixture(name: str, photo: np.ndarray, **meta) -> None:
    gray = cv2.cvtColor(photo, cv2.COLOR_BGR2GRAY)
    folder = ROOT / "tests" / "fixtures"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / f"{name}.gray.gz").write_bytes(gzip.compress(gray.tobytes(), 9, mtime=0))
    meta = {"width": gray.shape[1], "height": gray.shape[0], **meta}
    (folder / f"{name}.json").write_text(json.dumps(meta), encoding="utf-8", newline="\n")


def write_fixtures() -> None:
    rng = np.random.default_rng(3)

    def noisy(photo):
        return np.clip(photo + rng.normal(0, 4, photo.shape), 0, 255).astype(np.uint8)

    row = fx.row_canvas()
    save_fixture("door", noisy(fx.photograph(row, fx.DOOR_1, px_per_mm=1.3, skew=0.12)),
                 ids=[0, 1, 2, 3, 4, 5], px_per_mm=1.3)
    save_fixture("door-blurred",
                 noisy(fx.photograph(row, fx.DOOR_1, px_per_mm=1.3, skew=0.12, blur=15)),
                 ids=[0, 1, 2, 3, 4, 5], px_per_mm=1.3)
    save_fixture("two-doors-far", noisy(fx.photograph(row, fx.DOORS_1_2, px_per_mm=0.7)),
                 ids=list(range(9)), px_per_mm=0.7)
    save_fixture("no-stickers", noisy(fx.photograph(row, (60, 100, 330, 900), px_per_mm=1.3)),
                 ids=[], px_per_mm=1.3)

    boards = fx.make_board_layout()
    zone = next(z for z in boards.zones if z.kind == KIND_BOARD)
    cork = fx.draw_cork_board(boards, zone, {"a": ((560, 120, 210, 297), 1)})
    save_fixture("board-top-middle",
                 noisy(fx.photograph(cork, fx.BOARD_TOP_MIDDLE, px_per_mm=1.1, skew=0.05)),
                 ids=[221, 222], px_per_mm=1.1)
    save_fixture("board-top-left",
                 noisy(fx.photograph(cork, fx.BOARD_TOP_LEFT, px_per_mm=1.1, skew=0.05)),
                 ids=[220, 221, 228], px_per_mm=1.1)

    # Turned photos: a sticker must be found whichever way it is up.
    door = noisy(fx.photograph(row, fx.DOOR_1, px_per_mm=1.3, skew=0.12))
    save_fixture("door-sideways", cv2.rotate(door, cv2.ROTATE_90_CLOCKWISE),
                 ids=[0, 1, 2, 3, 4, 5], px_per_mm=1.3)
    height, width = door.shape[:2]
    turn = cv2.getRotationMatrix2D((width / 2, height / 2), 17, 0.8)
    save_fixture("door-tilted", cv2.warpAffine(door, turn, (width, height), borderValue=(90, 90, 90)),
                 ids=[0, 1, 2, 3, 4, 5], px_per_mm=1.3 * 0.8)


layout = load_layout()
write_dictionary(layout)
write_layout(layout)
write_fixtures()
